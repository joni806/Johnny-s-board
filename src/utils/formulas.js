/** חיפוש בכל הנוסחאות, לפי שם או לפי תוכן ה־LaTeX */
export function searchFormulas(query) {
    const q = String(query || '').trim().toLowerCase();
    if (!q) return FORMULA_GROUPS;
    return FORMULA_GROUPS
        .map((g) => ({ ...g, items: g.items.filter((it) => it.name.toLowerCase().includes(q) || it.tex.toLowerCase().includes(q) || g.label.includes(q)) }))
        .filter((g) => g.items.length > 0);
}
